// Builds src/data/dl1.js (RG.dlParts, RG.dlMind, RG.dlSkeleton) from the Deathless study notes.
// node src/i18n/dlbuild.js <notes dir>
const fs = require("fs"), path = require("path");
const dir = process.argv[2];
const TITLES = ["The Nature of the Law", "Rethinking the Crucifixion", "Interpreting the Bible", "Legalism and Identity", "The Priesthood and Covenant", "The Nature of the Church", "Spiritual Warfare Structures", "The Hope of the World"];
const parts = [];
for (let i = 1; i <= 8; i++) {
  const f = path.join(dir, "notes_part" + i + ".json");
  if (!fs.existsSync(f)) continue;
  const n = JSON.parse(fs.readFileSync(f, "utf8"));
  const sub = n.title && n.title !== TITLES[i - 1] ? n.title : "";
  parts.push({
    title: TITLES[i - 1] + (sub ? ": " + sub : ""), thesis: n.thesis, summary: n.summary,
    flow: n.flow || [], teachings: n.teachings || [], stories: n.stories || [], words: n.words || [],
    scriptures: n.scriptures || [], mindmap: n.mindmap || [], questions: n.questions || [], practice: n.practice || [], fair: n.fair || []
  });
}
const mind = parts.map((p, i) => ({ branch: (i + 1) + ". " + TITLES[i], leaves: [p.thesis].concat(p.mindmap.map(m => m.branch)) }));
const skel = parts.map((p, i) => ({ label: TITLES[i], tag: "Part " + (i + 1), text: p.thesis, ref: (p.scriptures || []).slice(0, 4).map(s => s.ref).join("; ") }));
const out = "window.RG = window.RG || {}; var RG = window.RG;\n/* Generated by src/i18n/dlbuild.js from the Deathless study notes. */\nRG.dlParts = " + JSON.stringify(parts, null, 1) + ";\nRG.dlMind = " + JSON.stringify(mind, null, 1) + ";\nRG.dlSkeleton = " + JSON.stringify(skel, null, 1) + ";\n";
fs.writeFileSync(path.join(__dirname, "..", "data", "dl1.js"), out);
const c = k => parts.reduce((a, p) => a + p[k].length, 0);
console.log("parts", parts.length, "teachings", c("teachings"), "stories", c("stories"), "scriptures", c("scriptures"), "words", c("words"), "fair", c("fair"), "questions", c("questions"));
